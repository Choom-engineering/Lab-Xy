"""Build an Open-XY send effect for the browser.

The Open-XY SDK's browser preview plays synths and drum kits only. A send effect
has a small interface (opxy/effect.hpp): State, initialize(State&) and
process(State&, [Buffer,] [const Transport&,] left, right, parameters), one
64-frame stereo Q31 block at a time. This wraps an effect's own fx.cpp, unchanged,
in a WebAssembly module LAB_XY's audio worklet drives:

    fx_left(), fx_right()   the two 64-word blocks, processed in place
    fx_parameters()         twelve words: the eight controls, then the shift row's
    fx_initialize()         a fresh State (and, on the device, an engine reset)
    fx_process()            one block
    fx_tempo(bpm_x10, ticks96, playing)   the transport, for tempo-aware effects

    python tools/effect_build.py <effect source folder> <out folder> <open-xy checkout>

writes engine.wasm and manifest.json. Needs Clang with the wasm32 target and wasm-ld.
"""
import json, pathlib, shutil, subprocess, sys

ADAPTER = r'''
// LAB_XY's browser host for one Open-XY send effect. Generated by tools/effect_build.py.
#include "fx.cpp"
using State = @NS@::State;
static State state;
static opxy::i32 left_block[64], right_block[64], words[12];
@BUFFER_DECL@
static opxy::Transport transport;
extern "C" {
opxy::i32* fx_left() { return left_block; }
opxy::i32* fx_right() { return right_block; }
opxy::i32* fx_parameters() { return words; }
opxy::u32 fx_state_bytes() { return sizeof(State); }
void fx_tempo(opxy::u32 bpm_x10, opxy::u32 ticks96, opxy::u32 playing) {
    transport.bpm_x10 = bpm_x10; transport.ticks96 = ticks96; transport.playing = playing != 0;
}
void fx_initialize() {
    state = State();
@BUFFER_CLEAR@
    @NS@::initialize(state);
}
void fx_process() {
    @NS@::process(state, @BUFFER_ARG@@TRANSPORT_ARG@left_block, right_block, words);
}
}
'''
EXPORTS = ['fx_left', 'fx_right', 'fx_parameters', 'fx_state_bytes', 'fx_tempo', 'fx_initialize', 'fx_process']
FLAGS = ['--target=wasm32', '-std=c++11', '-O2', '-ffreestanding', '-fno-exceptions', '-fno-rtti',
         '-fno-threadsafe-statics', '-fno-use-cxa-atexit', '-fno-c++-static-destructors', '-nostdlib', '-w']
MEMORY = 2 * 1024 * 1024


def clang():
    for c in ['clang++', 'clang']:
        if shutil.which(c): return c
    found = sorted(pathlib.Path('/usr/bin').glob('clang++-*')) + sorted(pathlib.Path('/usr/bin').glob('clang-*'))
    if found: return str(found[-1])
    raise RuntimeError('no Clang')


def build_effect(source, out, sdk):
    source, out, sdk = pathlib.Path(source).resolve(), pathlib.Path(out).resolve(), pathlib.Path(sdk).resolve()
    machine = json.loads((source / 'machine.json').read_text())
    definition = json.loads((source / 'definition.json').read_text())
    if machine.get('kind') != 'effect': raise RuntimeError('not an effect')
    ns, resources = definition['id'], definition.get('resources', {})
    words = resources.get('bufferBytes')
    out.mkdir(parents=True, exist_ok=True)
    adapter = ADAPTER.replace('@NS@', ns)
    if words:
        adapter = adapter.replace('@BUFFER_DECL@', f'static opxy::i32 scratch[{words // 4}];')
        adapter = adapter.replace('@BUFFER_CLEAR@', f'    for (opxy::u32 i = 0; i < {words // 4}u; ++i) scratch[i] = 0;')
        adapter = adapter.replace('@BUFFER_ARG@', f'opxy::Buffer{{scratch, {words // 4}u}}, ')
    else:
        adapter = adapter.replace('@BUFFER_DECL@', '').replace('@BUFFER_CLEAR@', '').replace('@BUFFER_ARG@', '')
    adapter = adapter.replace('@TRANSPORT_ARG@', 'transport, ' if resources.get('transport') else '')
    unit = out / 'fx_host.cpp'
    unit.write_text(adapter)
    paths = [sdk, sdk / 'sdk/include', sdk / 'sdk/platform/blackfin/freestanding', source,
             *(source / extra for extra in machine.get('includes', []))]
    units = [unit, *(source / s for s in machine.get('sources', [])), sdk / 'sdk/platform/blackfin/memory.cpp']
    command = [clang(), *FLAGS, *('-I' + str(p) for p in paths), *map(str, units), '-o', str(out / 'engine.wasm'),
               '-Wl,--no-entry', '-Wl,-z,stack-size=65536', f'-Wl,--initial-memory={MEMORY}', f'-Wl,--max-memory={MEMORY}',
               *('-Wl,--export=' + e for e in EXPORTS)]
    r = subprocess.run(command, capture_output=True, text=True, timeout=300)
    if r.returncode: raise RuntimeError('compile failed: ' + r.stderr.strip()[-600:])
    unit.unlink()
    manifest = dict(engine=ns, kind='effect', description=machine.get('description', ''), definition=definition,
                    busShift=resources.get('busShift', 0), transport=bool(resources.get('transport')),
                    dry=machine.get('dryParameter'))
    (out / 'manifest.json').write_text(json.dumps(manifest, separators=(',', ':')))
    return out


if __name__ == '__main__':
    print(build_effect(*sys.argv[1:4]))
