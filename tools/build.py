"""Build XY Studio's classic-script files, so the app also runs by double-clicking index.html.

    python tools/build.py

- app.bundle.js: the SDK browser modules, i18n.js and app.js joined into one classic script
  (browsers refuse ES modules from file://), plus the audio worklet source as text.
- machines/index.js and machines/<id>/data.js: the machine list and each machine's files as
  scripts (browsers refuse fetch() from file://). The hosted site keeps using the plain files.

Run it after changing app.js, i18n.js, worklet.js or the machines.
"""
import base64, json, pathlib, re

SITE = pathlib.Path(__file__).resolve().parent.parent

def module(path, imports):
    """Wrap an ES module as an IIFE returning its exports; imports come from earlier wrappers."""
    code = (SITE / path).read_text(encoding='utf-8')
    names = []
    def imp(m):
        names_in, source = m.group(1), m.group(2)
        key = re.sub(r'\?.*$', '', source.split('/')[-1])
        return f"const {{{names_in}}} = {imports[key]};"
    code = re.sub(r"^import\s*\{([^}]*)\}\s*from\s*'([^']+)';", imp, code, flags=re.M)
    def exp(m):
        names.append(m.group(2)); return m.group(1)
    code = re.sub(r"^export\s+((?:async\s+)?(?:function|class|const|let)\s+([A-Za-z_$][\w$]*))", exp, code, flags=re.M)
    return code, names

def wrap(var, path, imports):
    code, names = module(path, imports)
    imports[pathlib.Path(path).name] = var
    return f"const {var} = (() => {{\n'use strict';\n{code}\nreturn {{ {', '.join(names)} }};\n}})();\n"

def build_bundle():
    imports = {}
    parts = [
        wrap('__graphics', 'sdk/browser/graphics.mjs', imports),
        wrap('__controls', 'sdk/browser/controls.mjs', imports),
        wrap('__display', 'sdk/browser/display.mjs', imports),
        wrap('__i18n', 'i18n.js', imports),
    ]
    app, _ = module('app.js', imports)
    # Worklet as text: the SDK engine without its exports, then worklet.js without its import.
    engine = re.sub(r"^export\s+", '', (SITE / 'sdk/browser/engine.mjs').read_text(encoding='utf-8'), flags=re.M)
    worklet = re.sub(r"^import[^\n]*\n", '', (SITE / 'worklet.js').read_text(encoding='utf-8'), flags=re.M)
    header = ('// Generated by tools/build.py from app.js, i18n.js, worklet.js and sdk/browser/*.mjs. Do not edit.\n'
              '// The Open-XY SDK browser modules are MIT licensed (sdk/LICENSE.txt).\n')
    out = (header + f"window.XY_WORKLET_SRC = {json.dumps(engine + chr(10) + worklet)};\n" + ''.join(parts)
           + "(async () => {\n'use strict';\n" + app + "\n})().catch(e => { console.error(e); const t = document.getElementById('statusTxt'); if (t) t.textContent = String(e && e.message || e); });\n")
    (SITE / 'app.bundle.js').write_text(out, encoding='utf-8')
    return len(out)

def build_machines():
    mdir = SITE / 'machines'
    index = json.loads((mdir / 'index.json').read_text(encoding='utf-8'))
    (mdir / 'index.js').write_text('window.XY_MACHINE_INDEX = ' + json.dumps(index, ensure_ascii=False) + ';\n', encoding='utf-8')
    total = 0
    for m in index:
        d = mdir / m['id']
        manifest = json.loads((d / 'manifest.json').read_text(encoding='utf-8'))
        data = {
            'manifest': manifest,
            'wasm': base64.b64encode((d / 'engine.wasm').read_bytes()).decode(),
            'art': (d / 'panel.svg').read_text(encoding='utf-8'),
            'gray': (d / 'panel.grayscale.svg').read_text(encoding='utf-8') if (d / 'panel.grayscale.svg').exists() else None,
        }
        text = f"(window.XY_MACHINE_DATA = window.XY_MACHINE_DATA || {{}})[{json.dumps(m['id'])}] = {json.dumps(data, separators=(',', ':'))};\n"
        (d / 'data.js').write_text(text, encoding='utf-8')
        total += len(text)
    return len(index), total

if __name__ == '__main__':
    size = build_bundle()
    n, total = build_machines()
    print(f'app.bundle.js: {size // 1024} KB; {n} machine scripts: {total // 1024} KB')
